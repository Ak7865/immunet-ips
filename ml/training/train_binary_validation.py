
import json
import time
from collections import Counter
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import sklearn
from sklearn.ensemble import RandomForestClassifier
from sklearn.impute import SimpleImputer
from sklearn.metrics import (
    accuracy_score,
    classification_report,
    confusion_matrix,
)
from sklearn.model_selection import train_test_split
from sklearn.pipeline import Pipeline

PROJECT_ROOT = Path(__file__).resolve().parents[2]
PROCESSED_DIR = PROJECT_ROOT / "data" / "cicids2017" / "processed"
MODEL_DIR = PROJECT_ROOT / "ml" / "models"

MANIFEST_PATH = PROCESSED_DIR / "binary_validation_manifest.json"
MODEL_PATH = MODEL_DIR / "binary_random_forest_validation.joblib"
REPORT_PATH = PROCESSED_DIR / "binary_validation_report.json"

SOURCE_FILES = [
    "cleaned_Monday-WorkingHours.pcap_ISCX.csv",
    "cleaned_Tuesday-WorkingHours.pcap_ISCX.csv",
    "cleaned_Wednesday-workingHours.pcap_ISCX.csv",
    "cleaned_Thursday-WorkingHours-Afternoon-Infilteration.pcap_ISCX.csv",
    "cleaned_Thursday-WorkingHours-Morning-WebAttacks.pcap_ISCX.csv",
]

EXPECTED_FEATURES = 77
CHUNK_SIZE = 100_000
SAMPLE_SIZE = 300_000
RANDOM_SEED = 42
VALIDATION_FRACTION = 0.20


def load_reproducible_sample():
    """Reproduce the sample generated by create_validation_manifest.py."""
    rng = np.random.default_rng(RANDOM_SEED)

    sample_keys = np.empty(0, dtype=np.float64)
    sample_x = np.empty((0, EXPECTED_FEATURES), dtype=np.float32)
    sample_y = np.empty(0, dtype=np.int8)

    total_rows = 0

    for filename in SOURCE_FILES:
        path = PROCESSED_DIR / filename
        if not path.is_file():
            raise FileNotFoundError(f"Missing source file: {path}")

        print(f"Reading {filename}")

        for chunk in pd.read_csv(
            path,
            chunksize=CHUNK_SIZE,
            low_memory=False,
        ):
            if "Label" not in chunk.columns:
                raise ValueError(f"Label column missing in {filename}")

            labels = chunk["Label"].astype("string").str.strip()
            if labels.isna().any():
                raise ValueError(f"Missing labels found in {filename}")

            features = chunk.drop(columns=["Label"]).to_numpy(
                dtype=np.float32,
                copy=True,
            )

            if features.shape[1] != EXPECTED_FEATURES:
                raise ValueError(
                    f"{filename}: expected {EXPECTED_FEATURES} features, "
                    f"found {features.shape[1]}"
                )

            y = (labels != "BENIGN").to_numpy(dtype=np.int8)
            keys = rng.random(len(chunk))

            candidate_keys = np.concatenate((sample_keys, keys))
            candidate_x = np.concatenate((sample_x, features), axis=0)
            candidate_y = np.concatenate((sample_y, y), axis=0)

            keep = min(SAMPLE_SIZE, len(candidate_keys))

            if len(candidate_keys) > keep:
                selected = np.argpartition(candidate_keys, keep - 1)[:keep]
            else:
                selected = np.arange(keep)

            sample_keys = candidate_keys[selected]
            sample_x = candidate_x[selected]
            sample_y = candidate_y[selected]

            total_rows += len(chunk)

    if total_rows != 2_127_498:
        raise ValueError(
            f"Expected 2,127,498 source rows; found {total_rows:,}"
        )

    if len(sample_y) != SAMPLE_SIZE:
        raise RuntimeError(f"Expected {SAMPLE_SIZE:,} sampled rows.")

    print(f"\nSource rows scanned: {total_rows:,}")
    print(f"Reconstructed sample: {len(sample_y):,}")
    print(
        "Sample class counts:",
        {
            "BENIGN": int((sample_y == 0).sum()),
            "ATTACK": int((sample_y == 1).sum()),
        },
    )

    return sample_x, sample_y


def class_counts(y):
    return {
        "BENIGN": int((y == 0).sum()),
        "ATTACK": int((y == 1).sum()),
    }


def main():
    start_time = time.time()

    if not MANIFEST_PATH.is_file():
        raise FileNotFoundError(f"Manifest not found: {MANIFEST_PATH}")

    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))

    if manifest.get("sample_seed") != RANDOM_SEED:
        raise ValueError("Sample seed does not match the validation manifest.")

    if manifest.get("split_seed") != RANDOM_SEED:
        raise ValueError("Split seed does not match the validation manifest.")

    if manifest.get("sampled_rows") != SAMPLE_SIZE:
        raise ValueError("Sample size does not match the validation manifest.")

    x, y = load_reproducible_sample()

    # Recreate the same stratified split used by the manifest script.
    indices = np.arange(len(y))
    train_idx, val_idx = train_test_split(
        indices,
        test_size=VALIDATION_FRACTION,
        random_state=RANDOM_SEED,
        stratify=y,
    )

    x_train, x_val = x[train_idx], x[val_idx]
    y_train, y_val = y[train_idx], y[val_idx]

    # Fail safely if reconstruction differs from the saved manifest.
    checks = [
        (
            "training rows",
            len(train_idx),
            manifest["training"]["rows"],
        ),
        (
            "validation rows",
            len(val_idx),
            manifest["validation"]["rows"],
        ),
        (
            "training class counts",
            class_counts(y_train),
            manifest["training"]["binary_labels"],
        ),
        (
            "validation class counts",
            class_counts(y_val),
            manifest["validation"]["binary_labels"],
        ),
    ]

    for name, actual, expected in checks:
        if actual != expected:
            raise ValueError(
                f"Manifest mismatch for {name}: "
                f"actual={actual}, expected={expected}. "
                "Aborting before training."
            )

    print("\nPASS: reconstructed split matches the manifest.")
    print(f"Training rows: {len(y_train):,} | {class_counts(y_train)}")
    print(f"Validation rows: {len(y_val):,} | {class_counts(y_val)}")

    del x, y

    print("\nFitting validation candidate...")

    model = Pipeline(
        steps=[
            ("imputer", SimpleImputer(strategy="median")),
            (
                "classifier",
                RandomForestClassifier(
                    n_estimators=100,
                    max_depth=20,
                    min_samples_leaf=2,
                    random_state=RANDOM_SEED,
                    n_jobs=2,
                    class_weight=None,
                ),
            ),
        ]
    )

    # Only training partition data is used for fitting.
    model.fit(x_train, y_train)

    print("Predicting validation partition...")
    y_pred = model.predict(x_val).astype(np.int8)

    matrix = confusion_matrix(y_val, y_pred, labels=[0, 1])
    report = classification_report(
        y_val,
        y_pred,
        labels=[0, 1],
        target_names=["BENIGN", "ATTACK"],
        output_dict=True,
        zero_division=0,
    )

    accuracy = float(accuracy_score(y_val, y_pred))

    MODEL_DIR.mkdir(parents=True, exist_ok=True)
    joblib.dump(model, MODEL_PATH)

    result = {
        "experiment": "Monday-Thursday stratified validation candidate",
        "random_seed": RANDOM_SEED,
        "sample_rows": SAMPLE_SIZE,
        "training_rows": len(y_train),
        "validation_rows": len(y_val),
        "training_class_counts": class_counts(y_train),
        "validation_class_counts": class_counts(y_val),
        "features": EXPECTED_FEATURES,
        "model": {
            "type": "RandomForestClassifier",
            "n_estimators": 100,
            "max_depth": 20,
            "min_samples_leaf": 2,
            "n_jobs": 2,
            "class_weight": None,
        },
        "imputation": "median; fitted on training partition only",
        "accuracy": accuracy,
        "confusion_matrix_labels": ["BENIGN", "ATTACK"],
        "confusion_matrix": matrix.tolist(),
        "false_positives": int(matrix[0, 1]),
        "false_negatives": int(matrix[1, 0]),
        "classification_report": report,
        "scikit_learn_version": sklearn.__version__,
        "elapsed_seconds": round(time.time() - start_time, 2),
        "limitations": [
            "Uses a 300,000-row sample of Monday-Thursday records.",
            "Random row split can place records from the same capture in both partitions.",
            "Does not establish unseen-capture or unseen-attack-family generalization.",
            "Friday diagnostic data was not used for fitting or validation selection.",
        ],
    }

    REPORT_PATH.write_text(
        json.dumps(result, indent=2),
        encoding="utf-8",
    )

    print("\n========== VALIDATION RESULTS ==========")
    print("Confusion matrix (rows=actual, columns=predicted):")
    print("                 BENIGN  ATTACK")
    print(f"Actual BENIGN    {matrix[0, 0]:>6}  {matrix[0, 1]:>6}")
    print(f"Actual ATTACK    {matrix[1, 0]:>6}  {matrix[1, 1]:>6}")

    for label in ("BENIGN", "ATTACK", "macro avg", "weighted avg"):
        values = report[label]
        print(
            f"{label:12} "
            f"precision={values['precision']:.4f} "
            f"recall={values['recall']:.4f} "
            f"f1={values['f1-score']:.4f}"
        )

    print(f"\nAccuracy: {accuracy:.4f}")
    print(f"False positives: {matrix[0, 1]:,}")
    print(f"False negatives: {matrix[1, 0]:,}")
    print(f"Saved candidate model: {MODEL_PATH}")
    print(f"Saved validation report: {REPORT_PATH}")
    print(f"Elapsed seconds: {result['elapsed_seconds']:.2f}")


if __name__ == "__main__":
    main()
